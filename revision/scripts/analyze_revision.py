#!/usr/bin/env python3
"""Derive the revision tables from revision/data/ (promoted raw) and data/raw/ (E0).

Writes revision/results/*.csv, revision/results/summary.json and revision/results/tables.md.
Never writes outside revision/results/.
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "revision" / "data"
RES = ROOT / "revision" / "results"
NEUTRAL_ABS_GAS = 0  # a cell is "neutral" only when the delta is exactly zero


def load(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


def campaign_rows(cid: str) -> list[dict]:
    if cid == "E0":
        return load(ROOT / "data/raw/primary.jsonl") + load(ROOT / "data/raw/secondary.jsonl")
    rows = []
    for f in sorted((DATA / cid / "raw").glob("*.jsonl")):
        rows += load(f)
    return rows


def interactions(rows: list[dict]) -> dict:
    out = {}
    for r in rows:
        if r["record_kind"] == "interaction_tx":
            out[(r["condition_id"], r["implementation"])] = (r["complete_interaction_gas"], r["status"])
    return out


def steps(rows: list[dict]) -> dict:
    out = defaultdict(dict)
    for r in rows:
        out[(r["condition_id"], r["implementation"])][r["interaction_step"]] = r
    return out


def pct(b: int, m: int) -> float:
    return 100.0 * (b - m) / m


def write_csv(name: str, header: list[str], rows: list[list]) -> None:
    RES.mkdir(parents=True, exist_ok=True)
    with (RES / name).open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def md_table(header: list[str], rows: list[list]) -> str:
    def f(x):
        if isinstance(x, float):
            return f"{x:.3f}"
        return "" if x is None else str(x)
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(f(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def classify(delta: int) -> str:
    if delta > NEUTRAL_ABS_GAS:
        return "positive"
    if delta < -NEUTRAL_ABS_GAS:
        return "negative"
    return "neutral"


def main() -> None:
    md = ["# Revision tables (generated by revision/scripts/analyze_revision.py)\n"]
    summary = {}
    C = {c: campaign_rows(c) for c in ("E0", "E0R", "E1H", "E1", "E2")}
    I = {c: interactions(r) for c, r in C.items()}
    bad = {c: sorted({k for k, (_, s) in v.items() if s != "ok"}) for c, v in I.items()}
    summary["non_ok_cells"] = {c: [list(k) for k in v] for c, v in bad.items()}

    # --- E0 reproduction ------------------------------------------------------------------
    e0 = {(r["condition_id"], r["implementation"], r["interaction_step"]): r for r in C["E0"]}
    e0r = {(r["condition_id"], r["implementation"], r["interaction_step"]): r for r in C["E0R"]}
    diff_inter = [k for k in e0 if e0[k]["record_kind"] == "interaction_tx"
                  and e0[k]["transaction_gas_used"] != e0r[k]["transaction_gas_used"]]
    diff_dep = sorted({(k[1], k[2], e0[k]["transaction_gas_used"], e0r[k]["transaction_gas_used"])
                       for k in e0 if e0[k]["record_kind"] == "deployment"
                       and e0[k]["transaction_gas_used"] != e0r[k]["transaction_gas_used"]})
    summary["e0_reproduction"] = {
        "rows_e0": len(e0), "rows_e0r": len(e0r), "same_keys": set(e0) == set(e0r),
        "interaction_tx_gas_differences": len(diff_inter),
        "deployment_gas_differences": [list(x) for x in diff_dep],
    }
    md.append("## E0 reproduction (E0R vs data/raw)\n")
    md.append(f"Rows: {len(e0)} vs {len(e0r)}; interaction transactions with different gas: "
              f"**{len(diff_inter)}**. Deployment differences (metadata hash only): {diff_dep}.\n")

    # --- Primary / secondary overhead across campaigns -------------------------------------
    from frozen_shim import PRIMARY_IDS, SECONDARY_IDS  # noqa: E402

    hdr = ["condition_id", "matrix"]
    for c in ("E0", "E1H", "E1", "E2"):
        hdr += [f"{c}_blade", f"{c}_manual", f"{c}_overhead_pct"]
    hdr += ["hardfork_delta_blade", "hardfork_delta_manual", "payload_delta_blade", "core_delta_blade"]
    rows = []
    for matrix, ids in (("primary", PRIMARY_IDS), ("secondary", SECONDARY_IDS)):
        for cid in ids:
            r = [cid, matrix]
            for c in ("E0", "E1H", "E1", "E2"):
                b, m = I[c][(cid, "blade")][0], I[c][(cid, "manual")][0]
                r += [b, m, pct(b, m)]
            g = lambda c, i: I[c][(cid, i)][0]  # noqa: E731
            r += [g("E1H", "blade") - g("E0", "blade"), g("E1H", "manual") - g("E0", "manual"),
                  g("E1", "blade") - g("E1H", "blade"), g("E2", "blade") - g("E1", "blade")]
            rows.append(r)
    write_csv("overhead_by_campaign.csv", hdr, rows)
    prim = [r for r in rows if r[1] == "primary"]
    idx = {h: i for i, h in enumerate(hdr)}
    ranges = {}
    for c in ("E0", "E1H", "E1", "E2"):
        xs = [(r[idx[f"{c}_overhead_pct"]], r[0]) for r in prim]
        ranges[c] = {"min": min(xs), "max": max(xs)}
        req = [x for x in xs if x[1].startswith("REQ")]
        cn = [x for x in xs if x[1].startswith("CN")]
        ranges[c]["request"] = {"min": min(req), "max": max(req)}
        ranges[c]["contract_net"] = {"min": min(cn), "max": max(cn)}
    summary["primary_overhead_ranges"] = ranges
    md.append("## Complete-interaction gas and BLADE overhead by campaign\n")
    md.append("E0 submitted; E1H original Core + Cancun; E1 = E1H + no redundant inbound payload; "
              "E2 = corrected Core + corrected methodology.\n")
    md.append(md_table(["condition", "E0 %", "E1H %", "E1 %", "E2 %", "E2 blade", "E2 manual",
                        "hardfork Δ blade", "hardfork Δ manual", "payload Δ blade", "core Δ blade"],
                       [[r[0], r[idx["E0_overhead_pct"]], r[idx["E1H_overhead_pct"]], r[idx["E1_overhead_pct"]],
                         r[idx["E2_overhead_pct"]], r[idx["E2_blade"]], r[idx["E2_manual"]],
                         r[idx["hardfork_delta_blade"]], r[idx["hardfork_delta_manual"]],
                         r[idx["payload_delta_blade"]], r[idx["core_delta_blade"]]] for r in rows]))
    md.append("\nPrimary overhead ranges: " + "; ".join(
        f"{c}: {v['min'][0]:.3f}% ({v['min'][1]}) to {v['max'][0]:.3f}% ({v['max'][1]})" for c, v in ranges.items()) + "\n")

    # --- Step-level Request costs (E1 vs E2) ----------------------------------------------
    S = {c: steps(C[c]) for c in ("E0R", "E1", "E2")}
    st_rows = []
    for cid in ("REQ-R1-P0", "REQ-R2-P0", "REQ-R3-P0", "REQ-R4-P0", "REQ-R3-P1024"):
        for step in ("deploy_initiator", "deploy_participant", "startRequest", "agree", "refuse", "inform", "failure"):
            a = S["E1"][(cid, "blade")].get(step)
            b = S["E2"][(cid, "blade")].get(step)
            m = S["E2"][(cid, "manual")].get(step)
            if not a:
                continue
            st_rows.append([cid, step, a["transaction_gas_used"], b["transaction_gas_used"],
                            b["transaction_gas_used"] - a["transaction_gas_used"],
                            m["transaction_gas_used"] if m else None])
    write_csv("request_steps_E1_E2.csv", ["condition_id", "step", "E1_blade", "E2_blade", "delta", "E2_manual"], st_rows)
    md.append("\n## Request per-transaction gas, E1 vs E2 (BLADE)\n")
    md.append(md_table(["condition", "step", "E1", "E2", "Δ", "manual"], st_rows))

    # Marginal (steady-state) cost per additional active conversation from the K series.
    k_rows = []
    for c in ("E1", "E2"):
        for impl in ("blade", "manual"):
            g = {k: I[c][(f"SEC-ACT-K{k}", impl)][0] for k in (1, 10, 100)}
            k_rows.append([c, impl, g[1], g[10], g[100], (g[100] - g[10]) / 90])
    write_csv("active_k_marginal.csv", ["campaign", "impl", "K1", "K10", "K100", "marginal_per_conversation_K10_K100"], k_rows)
    md.append("\n## Active Request conversations (start + agree), marginal cost per conversation\n")
    md.append(md_table(["campaign", "impl", "K=1", "K=10", "K=100", "marginal (K10→K100)/90"], k_rows))
    s2 = S["E2"][("SEC-ACT-K100", "blade")]
    s1 = S["E1"][("SEC-ACT-K100", "blade")]
    first = [s2["startRequest"]["transaction_gas_used"], s1["startRequest"]["transaction_gas_used"]]
    later = [s2["startRequest_50"]["transaction_gas_used"], s1["startRequest_50"]["transaction_gas_used"]]
    summary["start_request_first_vs_steady"] = {
        "E2_first": first[0], "E1_first": first[1], "E2_steady(startRequest_50)": later[0],
        "E1_steady(startRequest_50)": later[1], "first_delta": first[0] - first[1], "steady_delta": later[0] - later[1],
    }
    md.append(f"\nstartRequest first vs steady state (K=100 cell): {summary['start_request_first_vs_steady']}\n")

    # --- Deployment ----------------------------------------------------------------------
    dep_rows = []
    for name, step, cid in (("BladeRequester", "deploy_initiator", "REQ-R1-P0"),
                            ("BladeParticipant", "deploy_participant", "REQ-R1-P0"),
                            ("ManualInitiator", "deploy_initiator", "REQ-R1-P0"),
                            ("ManualParticipant", "deploy_participant", "REQ-R1-P0"),
                            ("BladeManager", "deploy_manager", "CN-A-N1-P0"),
                            ("BladeCnParticipant", "deploy_participant_0", "CN-A-N1-P0"),
                            ("ManualManager", "deploy_manager", "CN-A-N1-P0"),
                            ("ManualCnParticipant", "deploy_participant_0", "CN-A-N1-P0")):
        impl = "blade" if name.startswith("Blade") else "manual"
        vals = []
        for c in ("E0", "E0R", "E1", "E2"):
            r = steps(C[c])[(cid, impl)][step]
            vals += [r["transaction_gas_used"], r.get("runtime_bytecode_bytes")]
        dep_rows.append([name] + vals)
    write_csv("deployment.csv", ["contract", "E0_gas", "E0_runtime", "E0R_gas", "E0R_runtime", "E1_gas", "E1_runtime",
                                 "E2_gas", "E2_runtime"], dep_rows)
    md.append("\n## Deployment gas and runtime bytecode bytes\n")
    md.append(md_table(["contract", "E0 gas", "E0 runtime", "E0R gas", "E0R runtime", "E1 gas", "E1 runtime",
                        "E2 gas", "E2 runtime"], dep_rows))

    # --- Variants: events and purpose-built guarantees ------------------------------------
    var = {}
    for c in ("E2-MCORR", "E2-MOBS", "E2-MCOBS", "E2-EV-NORECV", "E2-EV-NOPHASE", "E2-EV-NONE"):
        if (DATA / c).is_dir():
            var[c] = interactions(campaign_rows(c))
    ev_ids = sorted({cid for (cid, _) in var.get("E2-EV-NONE", {})})
    ev_rows = []
    for cid in ev_ids:
        b = I["E2"][(cid, "blade")][0]
        m = I["E2"][(cid, "manual")][0]
        mo = var["E2-MOBS"][(cid, "manual")][0]
        r = [cid, b]
        for c in ("E2-EV-NORECV", "E2-EV-NOPHASE", "E2-EV-NONE"):
            r.append(var[c][(cid, "blade")][0])
        r += [m, mo, pct(b, m), pct(var["E2-EV-NONE"][(cid, "blade")][0], m), pct(b, mo),
              100.0 * (b - var["E2-EV-NONE"][(cid, "blade")][0]) / b]
        ev_rows.append(r)
    ev_hdr = ["condition_id", "blade_E2", "blade_noReceived", "blade_noPhase", "blade_noEvents", "manual_E2",
              "manual_observable", "overhead_E2_pct", "overhead_noEvents_vs_manual_pct",
              "overhead_E2_vs_manual_observable_pct", "event_share_of_blade_pct"]
    write_csv("events.csv", ev_hdr, ev_rows)
    md.append("\n## Event cost (E2 basis)\n")
    md.append(md_table(ev_hdr, ev_rows))

    corr_rows = []
    for (cid, impl), (g, _) in sorted(var.get("E2-MCORR", {}).items()):
        if impl != "manual" or not cid.startswith(("REQ", "SEC-ACT")):
            continue
        m = I["E2"][(cid, "manual")][0]
        b = I["E2"][(cid, "blade")][0]
        corr_rows.append([cid, b, m, g, g - m, pct(b, m), pct(b, g)])
    corr_hdr = ["condition_id", "blade_E2", "manual_E2", "manual_correlated", "correlation_cost_manual",
                "overhead_vs_manual_pct", "overhead_vs_manual_correlated_pct"]
    write_csv("manual_correlated.csv", corr_hdr, corr_rows)
    md.append("\n## Purpose-built baseline with the same correlation guarantee (sensitivity)\n")
    md.append(md_table(corr_hdr, corr_rows))

    if "E2-MCOBS" in var:
        fair_rows = []
        for (cid, impl), (g, _) in sorted(var["E2-MCOBS"].items()):
            if impl != "manual":
                continue
            b = I["E2"][(cid, "blade")][0]
            m = I["E2"][(cid, "manual")][0]
            mc = var["E2-MCORR"].get((cid, "manual"), (None,))[0]
            mo = var["E2-MOBS"].get((cid, "manual"), (None,))[0]
            fair_rows.append([cid, b, m, mc, mo, g, pct(b, m),
                              pct(b, mc) if mc else None, pct(b, mo) if mo else None, pct(b, g)])
        fair_hdr = ["condition_id", "blade_E2", "manual", "manual_correlated", "manual_observable",
                    "manual_correlated_observable", "overhead_vs_manual_pct", "overhead_vs_correlated_pct",
                    "overhead_vs_observable_pct", "overhead_vs_correlated_observable_pct"]
        write_csv("baseline_sensitivity.csv", fair_hdr, fair_rows)
        req = [r for r in fair_rows if r[0].startswith("REQ") and r[0] in PRIMARY_IDS]
        cn = [r for r in fair_rows if r[0].startswith("CN") and r[0] in PRIMARY_IDS]
        summary["baseline_sensitivity_primary"] = {
            name: {"vs_manual": [min(r[6] for r in rs), max(r[6] for r in rs)],
                   "vs_correlated_observable": [min(r[9] for r in rs), max(r[9] for r in rs)]}
            for name, rs in (("request", req), ("contract_net", cn)) if rs}
        md.append("\n## BLADE E2 overhead against each baseline (sensitivity to baseline guarantees)\n")
        md.append(md_table(fair_hdr, fair_rows))

    # --- Ablation --------------------------------------------------------------------------
    hist = json.loads((ROOT / "ablation/raw/ablation.json").read_text())["results"]
    abl = {}
    for a in ("ABL-E0R", "ABL-E1", "ABL-E2"):
        p = DATA / a / "ablation.json"
        if p.is_file():
            abl[a] = json.loads(p.read_text())["results"]
    gas = lambda cell: int(cell["complete_interaction_gas"])  # noqa: E731
    if "ABL-E0R" in abl:
        mism = [(v, c, gas(hist[v][c]), gas(abl["ABL-E0R"][v][c])) for v in hist for c in hist[v]
                if gas(hist[v][c]) != gas(abl["ABL-E0R"][v][c])]
        summary["ablation_reproduction_mismatches"] = mism
        md.append(f"\n## Ablation reproduction (ABL-E0R vs ablation/raw/ablation.json)\n\nMismatching cells: {mism}\n")
    a_rows = []
    for a, res in [("E0 (submitted)", hist)] + list(abl.items()):
        if a == "ABL-E0R":
            continue
        for v in ("A1", "A2", "A3", "A4", "A5", "A34"):
            for c in sorted(res.get(v, {})):
                g0, gi = gas(res["A0"][c]), gas(res[v][c])
                a_rows.append([a, v, c, g0, gi, gi - g0, 100.0 * (gi - g0) / g0, classify(gi - g0)])
    a_hdr = ["campaign", "factor", "cell", "A0_gas", "variant_gas", "delta", "relative_effect_pct", "direction"]
    write_csv("ablation_effects.csv", a_hdr, a_rows)
    md.append("\n## Ablation effects (variant − A0, same harness; positive = the Core optimisation saves gas)\n")
    md.append(md_table(a_hdr, a_rows))
    dir_summary = defaultdict(lambda: defaultdict(int))
    for r in a_rows:
        dir_summary[f"{r[0]}/{r[1]}"][r[7]] += 1
    summary["ablation_direction_counts"] = {k: dict(v) for k, v in dir_summary.items()}

    int_rows = []
    for a, res in [("E0 (submitted)", hist)] + [(k, v) for k, v in abl.items() if k != "ABL-E0R"]:
        for c in sorted(res.get("A34", {})):
            if c not in res.get("A3", {}) or c not in res.get("A4", {}):
                int_rows.append([a, c, None, None, gas(res["A34"][c]) - gas(res["A0"][c]), None, "A3 or A4 not measured"])
                continue
            g0 = gas(res["A0"][c])
            d3, d4, d34 = gas(res["A3"][c]) - g0, gas(res["A4"][c]) - g0, gas(res["A34"][c]) - g0
            int_rows.append([a, c, d3, d4, d34, d34 - d3 - d4, ""])
    int_hdr = ["campaign", "cell", "delta_A3", "delta_A4", "delta_A34", "interaction_A34_minus_A3_minus_A4", "note"]
    write_csv("ablation_interaction.csv", int_hdr, int_rows)
    md.append("\n## A3 × A4 interaction (A34 − A3 − A4, deltas vs A0)\n")
    md.append(md_table(int_hdr, int_rows))

    # --- Storage probes --------------------------------------------------------------------
    st = {}
    for c in ("E1", "E2", "E2-MCORR", "E2-MCOBS"):
        d = DATA / c / "storage"
        if d.is_dir():
            st[c] = {f.name: json.loads(f.read_text()) for f in sorted(d.glob("revision_*.json"))}
    summary["storage"] = st

    (RES / "summary.json").write_text(json.dumps(summary, indent=2, default=list) + "\n")
    (RES / "tables.md").write_text("\n".join(md) + "\n")
    print("wrote", RES)


if __name__ == "__main__":
    main()
